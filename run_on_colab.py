def create_overlay(slice_u8, z_slice):
    base = np.rot90(slice_u8).astype(np.float32) / 255.0
    z_rot = np.rot90(z_slice)
    rgb = np.stack([base, base, base], axis=-1)

    alpha = np.clip((z_rot - 3.0) / 3.0, 0.0, 1.0)
    mask = alpha > 0
    rgb[mask, 0] = (1.0 - alpha[mask]) * rgb[mask, 0] + alpha[mask] * 1.0
    rgb[mask, 1] = (1.0 - alpha[mask]) * rgb[mask, 1] + alpha[mask] * 0.15
    rgb[mask, 2] = (1.0 - alpha[mask]) * rgb[mask, 2] + alpha[mask] * 0.15
    return np.clip(rgb, 0.0, 1.0)

